def translate_statute_entry(
    doc_id: str = "",
    title: str = "",
    section_num: str = "",
    snippet: str = "",
    lang: str = "ru",
    official_title: str = "",
    **kwargs
) -> Dict[str, Any]:
    if not title and official_title:
        title = official_title
    search_key = f"{doc_id} {title} {section_num} {snippet}".lower()
    
    for kb_key, kb_data in STATUTE_KNOWLEDGE_BASE.items():
        if any(term in search_key for term in kb_data["match"]):
            lang_data = kb_data.get(lang, kb_data["en"])
            return {
                "id": kb_key,
                "title": lang_data["title"],
                "section": lang_data["section"],
                "summary": lang_data["summary"],
                "full_text": lang_data["full_text"],
                "official_th": kb_data.get("official_title", ""),
                "official_th_section": kb_data.get("official_th_section", ""),
                "official_th_text": kb_data.get("official_th_text", "")
            }
            
    # Domain fallbacks
    if any(k in search_key for k in ["condo", "квартир", "кондо", "19", "квот", "juristic"]):
        kb_data = STATUTE_KNOWLEDGE_BASE["CONDO_ACT_19"]
    elif any(k in search_key for k in ["tax", "налог", "สรรพากร", "p.161", "p.162"]):
        kb_data = STATUTE_KNOWLEDGE_BASE["REVENUE_CODE_41"]
    elif any(k in search_key for k in ["labor", "труд", "увольнен", "пособие", "118"]):
        kb_data = STATUTE_KNOWLEDGE_BASE["LABOR_PROTECTION_118"]
    elif any(k in search_key for k in ["fba", "номинал", "компани", "бизнес", "36"]):
        kb_data = STATUTE_KNOWLEDGE_BASE["FBA_4_36"]
    elif any(k in search_key for k in ["superficies", "суперфиций", "1410"]):
        kb_data = STATUTE_KNOWLEDGE_BASE["CCC_1410_SUPERFICIES"]
    elif any(k in search_key for k in ["lease", "аренд", "538", "540"]):
        kb_data = STATUTE_KNOWLEDGE_BASE["CCC_538_LEASEHOLD"]
    else:
        kb_data = STATUTE_KNOWLEDGE_BASE["LAND_CODE_86"]

    lang_data = kb_data.get(lang, kb_data["en"])
    return {
        "id": kb_data.get("official_title", doc_id or "STATUTE_OFFICIAL"),
        "title": lang_data["title"],
        "section": lang_data["section"],
        "summary": lang_data["summary"],
        "full_text": lang_data["full_text"],
        "official_th": kb_data.get("official_title", ""),
        "official_th_section": kb_data.get("official_th_section", ""),
        "official_th_text": kb_data.get("official_th_text", "")
    }


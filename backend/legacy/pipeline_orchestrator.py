# 3. QUERY DECOMPOSITION ENGINE
# ─────────────────────────────────────────────────────────────────────────────
def decompose_query_facets(query: str) -> Dict[str, Any]:
    """
    Decomposes complex, multi-part, or comparative legal inquiries into:
    - Target entities (e.g. ['DTV', 'LTR'], ['FREEHOLD', 'LEASEHOLD'])
    - Sub-intent questions (e.g. ['FINANCIAL_REQUIREMENTS', 'WORK_RIGHTS'])
    - Is comparative question (Boolean)
    - Primary and secondary domains
    """
    q_lower = query.lower()
    
    matched_entities = []
    for ent, keywords in LEGAL_ENTITIES.items():
        if any(k in q_lower for k in keywords):
            matched_entities.append(ent)
            
    matched_facets = []
    for facet, keywords in QUESTION_FACETS.items():
        if any(k in q_lower for k in keywords):
            matched_facets.append(facet)
            
    is_comparison = "COMPARISON" in matched_facets or len(matched_entities) >= 2 or any(
        w in q_lower for w in ["разница", "отличие", "сравн", "чем отличается", "что лучше", " vs ", " или "]
    )
    
    primary_domain = "CIVIL_COMMERCIAL"
    if any(e in matched_entities for e in ["DTV", "LTR", "ELITE", "WORK_PERMIT", "RETIREMENT", "SMART_VISA"]):
        primary_domain = "IMMIGRATION_VISA"
    elif any(e in matched_entities for e in ["FREEHOLD", "LEASEHOLD", "CONDO", "LAND", "VILLA", "SUPERFICIES", "FET"]):
        primary_domain = "REAL_ESTATE"
    elif any(e in matched_entities for e in ["FBA", "NOMINEE", "BOI", "THAI_COMPANY"]):
        primary_domain = "CORPORATE_FBA"
    elif any(e in matched_entities for e in ["TAX_RESIDENCY", "FOREIGN_REMITTANCE", "DTA", "PIT"]):
        primary_domain = "TAX_RESIDENCY"
    elif any(e in matched_entities for e in ["SEVERANCE", "LABOR_CONTRACT"]):
        primary_domain = "LABOR_LAW"
        
    return {
        "raw_query": query,
        "entities": matched_entities,
        "facets": matched_facets,
        "is_comparison": is_comparison,
        "primary_domain": primary_domain
    }


def enrich_text_with_inline_statute_links(text: str) -> str:
    """
    Substitutes statute citations in text with clickable interactive badges.
    In Web App: rendered as <a href="javascript:void(0)" class="statute-inline-link" onclick="openStatuteModalByKey('KEY')">...</a>
    """
    processed = text
    applied_keys = set()
    
    for pattern, key, label in STATUTE_LINK_PATTERNS:
        def repl(match):
            m_text = match.group(1)
            start_pos = match.start()
            pre = text[max(0, start_pos - 15):start_pos]
            if "onclick=" in pre or "href=" in pre or "openStatuteModalByKey" in pre:
                return m_text
            applied_keys.add(key)
            return '<a href="javascript:void(0)" class="statute-inline-link" onclick="openStatuteModalByKey(\'' + key + '\')" title="Открыть официальный текст закона">' + m_text + '</a>'

        processed = re.sub(pattern, repl, processed, flags=re.IGNORECASE)

    return processed

